#!/usr/bin/env python3
"""Generate the effect-free TypeScript DTOs from the closed wire schema."""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
schema = json.loads((root / 'contracts/v1/schema.json').read_text())

def render(s):
    if '$ref' in s:
        return s['$ref'].split('/')[-1]
    if 'oneOf' in s:
        return ' | '.join(render(x) for x in s['oneOf'])
    if 'const' in s:
        return json.dumps(s['const'])
    if 'enum' in s:
        return ' | '.join(json.dumps(x) for x in s['enum'])
    if s['type'] == 'string':
        return 'string'
    if s['type'] == 'object':
        assert s['additionalProperties'] is False
        assert set(s['required']) == set(s['properties'])
        return '{ ' + '; '.join(f'{json.dumps(k)}: {render(v)}' for k, v in s['properties'].items()) + ' }'
    raise ValueError('unsupported schema')

declarations = []
for name, definition in schema['$defs'].items():
    typ = render(definition)
    if name in ('Id', 'Counter'):
        typ += f' & {{ readonly __{name.lower()}: unique symbol }}'
    declarations.append(f'export type {name} = {typ};')
declarations.append(f'export type Envelope = {render(schema)};')
output = '// Generated by scripts/generate-dtos.py; do not edit.\n' + '\n\n'.join(declarations) + '\n'
path = root / 'packages/pi-worker/src/dto.ts'
if '--check' in sys.argv:
    if path.read_text() != output:
        raise SystemExit('DTOs differ; run scripts/generate-dtos.py')
else:
    path.write_text(output)

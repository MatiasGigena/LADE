#!/usr/bin/env python3
"""Generate the effect-free TypeScript DTOs from both closed wire schemas (client and worker)."""
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parent.parent
client = json.loads((root / 'contracts/v1/schema.json').read_text())
worker = json.loads((root / 'contracts/v1/worker-schema.json').read_text())


def render(s):
    if '$ref' in s:
        return s['$ref'].split('/')[-1]
    if 'oneOf' in s:
        return ' | '.join(render(x) for x in s['oneOf'])
    if 'const' in s:
        return json.dumps(s['const'])
    if 'enum' in s:
        return ' | '.join(json.dumps(x) for x in s['enum'])
    if s['type'] in ('string', 'boolean'):
        return s['type']
    if s['type'] == 'array':
        item = render(s['items'])
        return f'({item})[]' if '|' in item else f'{item}[]'
    if s['type'] == 'object':
        assert s['additionalProperties'] is False and set(s['required']) <= set(s['properties'])
        fields = [f'{json.dumps(k)}{"" if k in s["required"] else "?"}: {render(v)}'
                  for k, v in s['properties'].items()]
        return '{ ' + '; '.join(fields) + ' }' if fields else 'Record<never, never>'
    raise ValueError('unsupported schema')


definitions = dict(client['$defs'])
for name, definition in worker['$defs'].items():
    # Shared names must denote the same wire shape in both contracts.
    assert definitions.setdefault(name, definition) == definition, name
declarations = []
for name, definition in definitions.items():
    typ = render(definition)
    if name in ('Id', 'Counter'):
        typ += f' & {{ readonly __{name.lower()}: unique symbol }}'
    declarations.append(f'export type {name} = {typ};')
declarations.append(f'export type Envelope = {render(client)};')
declarations.append(f'export type WorkerEnvelope = {render(worker)};')
output = '// Generated by scripts/generate-dtos.py; do not edit.\n' + '\n\n'.join(declarations) + '\n'
path = root / 'packages/pi-worker/src/dto.ts'
if '--check' in sys.argv:
    if path.read_text() != output:
        raise SystemExit('DTOs differ; run scripts/generate-dtos.py')
else:
    path.write_text(output)
